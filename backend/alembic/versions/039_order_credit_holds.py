# ---------------------------------------------------------------------------
# Phase B: C3 backfill (created_by IS NULL marks the synthetic snapshot)
# ---------------------------------------------------------------------------


def _backfill_holds(bind, schema: str) -> None:
    q_orders = f'"{schema}".orders'
    q_payments = f'"{schema}".payments'
    q_holds = f'"{schema}".order_credit_holds'
    bind.execute(sa.text(f"""
        WITH {EFFECTIVE_PER_ORDER.format(payments=q_payments)}
        INSERT INTO {q_holds}
            (order_id, amount, remaining_amount, status, created_by)
        SELECT o.id,
               o.total_amount,
               CASE WHEN o.status::text IN ('confirmed', 'partially_paid')
                    THEN o.total_amount - COALESCE(e.cash_total, 0)
                    ELSE 0 END,
               CASE
                   WHEN COALESCE(e.credit_total, 0) > 0 THEN 'converted'
                   WHEN o.status::text IN ('confirmed', 'partially_paid')
                       THEN 'active'
                   ELSE 'settled'
               END,
               NULL
        FROM {q_orders} o
        LEFT JOIN effective_payments e ON e.order_id = o.id
        WHERE o.is_deleted IS FALSE
          AND o.status::text IN ('confirmed', 'partially_paid',
                                 'paid', 'fulfilled', 'returned')
    """))


# ---------------------------------------------------------------------------
# Phase R: binding cache rebuild (per-order first, retailer SUM second)
# ---------------------------------------------------------------------------


def _rebuild_binding_cache(bind, schema: str, ws: str) -> None:
    q_orders = f'"{schema}".orders'
    q_payments = f'"{schema}".payments'
    q_holds = f'"{schema}".order_credit_holds'
    params = {"ws": ws}
    bind.execute(sa.text(f"""
        WITH {EFFECTIVE_PER_ORDER.format(payments=q_payments)},
        holds AS (
            SELECT o.retailer_id::text AS retailer_id,
                   SUM(h.remaining_amount) AS hold_total
            FROM {q_holds} h
            JOIN {q_orders} o ON o.id = h.order_id AND o.is_deleted IS FALSE
            WHERE h.status = 'active'
            GROUP BY o.retailer_id
        ),
        exposure AS (
            SELECT o.retailer_id::text AS retailer_id,
                   SUM(e.credit_total - e.cash_total) AS exposure_total
            FROM {q_orders} o
            JOIN effective_payments e ON e.order_id = o.id
            WHERE o.is_deleted IS FALSE
              AND e.credit_total > 0
            GROUP BY o.retailer_id
        )
        UPDATE public.wholesaler_retailer_bindings wrb
        SET outstanding_balance = target.new_balance::numeric(12, 2),
            updated_at = now()
        FROM (
            SELECT r.retailer_id,
                   (COALESCE(h.hold_total, 0)
                    + COALESCE(x.exposure_total, 0)) AS new_balance
            FROM (
                SELECT retailer_id FROM holds
                UNION
                SELECT retailer_id FROM exposure
            ) r
            LEFT JOIN holds h ON h.retailer_id = r.retailer_id
            LEFT JOIN exposure x ON x.retailer_id = r.retailer_id
        ) target
        WHERE wrb.retailer_id::text = target.retailer_id
          AND wrb.wholesaler_id::text = :ws
          AND wrb.is_deleted IS FALSE
    """), params)
    # bindings with no qualifying orders zero out (phantom coverage)
    bind.execute(sa.text(f"""
        UPDATE public.wholesaler_retailer_bindings wrb
        SET outstanding_balance = 0, updated_at = now()
        WHERE wrb.wholesaler_id::text = :ws
          AND wrb.is_deleted IS FALSE
          AND NOT EXISTS (
              SELECT 1 FROM {q_orders} o
              WHERE o.retailer_id = wrb.retailer_id
                AND o.is_deleted IS FALSE
          )
    """), params)


# ---------------------------------------------------------------------------
# Phase V: verification (interlocked with P14)
# ---------------------------------------------------------------------------


def _verify_tenant(bind, schema: str, ws: str) -> None:
    q_orders = f'"{schema}".orders'
    q_payments = f'"{schema}".payments'
    q_holds = f'"{schema}".order_credit_holds'
    params = {"ws": ws}

    row_violations = _count(bind, f"""
        WITH {EFFECTIVE_PER_ORDER.format(payments=q_payments)},
        expected AS (
            SELECT o.id,
                   o.total_amount,
                   CASE WHEN COALESCE(e.credit_total, 0) > 0 THEN 'converted'
                        WHEN o.status::text IN ('confirmed', 'partially_paid')
                            THEN 'active'
                        ELSE 'settled' END AS status,
                   CASE WHEN o.status::text IN ('confirmed', 'partially_paid')
                             AND COALESCE(e.credit_total, 0) = 0
                        THEN o.total_amount - COALESCE(e.cash_total, 0)
                        ELSE 0 END AS remaining
            FROM {q_orders} o
            LEFT JOIN effective_payments e ON e.order_id = o.id
            WHERE o.is_deleted IS FALSE
              AND o.status::text IN ('confirmed', 'partially_paid',
                                     'paid', 'fulfilled', 'returned')
        )
        SELECT COUNT(*) FROM expected ex
        FULL OUTER JOIN {q_holds} h ON h.order_id = ex.id
        WHERE h.id IS NULL
           OR ex.id IS NULL
           OR h.amount <> ex.total_amount
           OR h.remaining_amount <> ex.remaining
           OR h.status <> ex.status
    """, params)
    if row_violations:
        raise PreflightFailure(
            f"{schema}: V-verify row check failed for {row_violations} "
            "lifecycle row(s) (backfill does not match the C3 matrix)")

    aggregate_violations = _count(bind, f"""
        WITH {EFFECTIVE_PER_ORDER.format(payments=q_payments)},
        holds AS (
            SELECT o.retailer_id::text AS retailer_id,
                   SUM(h.remaining_amount) AS hold_total
            FROM {q_holds} h
            JOIN {q_orders} o ON o.id = h.order_id AND o.is_deleted IS FALSE
            WHERE h.status = 'active'
            GROUP BY o.retailer_id
        ),
        exposure AS (
            SELECT o.retailer_id::text AS retailer_id,
                   SUM(e.credit_total - e.cash_total) AS exposure_total
            FROM {q_orders} o
            JOIN effective_payments e ON e.order_id = o.id
            WHERE o.is_deleted IS FALSE AND e.credit_total > 0
            GROUP BY o.retailer_id
        )
        SELECT COUNT(*)
        FROM public.wholesaler_retailer_bindings wrb
        LEFT JOIN holds h ON h.retailer_id = wrb.retailer_id::text
        LEFT JOIN exposure x ON x.retailer_id = wrb.retailer_id::text
        WHERE wrb.is_deleted IS FALSE
          AND wrb.wholesaler_id::text = :ws
          AND wrb.outstanding_balance
              <> (COALESCE(h.hold_total, 0)
                  + COALESCE(x.exposure_total, 0))::numeric(12, 2)
    """, params)
    if aggregate_violations:
        raise PreflightFailure(
            f"{schema}: V-verify aggregate check failed for "
            f"{aggregate_violations} binding(s) (cache != holds + exposure)")

    negatives = _count(
        bind,
        "SELECT COUNT(*) FROM public.wholesaler_retailer_bindings "
        "WHERE is_deleted IS FALSE AND wholesaler_id::text = :ws "
        "AND outstanding_balance < 0",
        params,
    )
    if negatives:
        raise PreflightFailure(
            f"{schema}: {negatives} negative binding cache value(s) remain")


# ---------------------------------------------------------------------------
# catalog helpers
# ---------------------------------------------------------------------------


def _table_exists(bind, schema: str, table: str) -> bool:
    # pg_catalog, not information_schema: the migration authority must see
    # app-owned tenant tables even though privilege-filtered views hide them
    # (G1-R2E-P1R1 authority contract; genuinely absent tables are still
    # rejected by name through the same call sites).
    return bool(
        bind.execute(
            sa.text(
                "SELECT 1 FROM pg_catalog.pg_class c "
                "JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace "
                "WHERE n.nspname=:schema AND c.relname=:table "
                "AND c.relkind IN ('r', 'p', 'v', 'f')"
            ),
            {"schema": schema, "table": table},
        ).scalar()
    )


def _count(bind, sql: str, params: dict[str, Any] | None = None) -> int:
    return int((bind.execute(sa.text(sql), params or {}).scalar()) or 0)
