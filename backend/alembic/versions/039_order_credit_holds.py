def _preflight_tenant(bind, schema: str) -> None:
    for table in ("orders", "payments"):
        if not _table_exists(bind, schema, table):
            raise PreflightFailure(f"{schema}.{table} is missing")
    if _table_exists(bind, schema, "order_credit_holds"):
        raise PreflightFailure(
            f"{schema}: partial or pre-existing R2 schema detected "
            "(order_credit_holds already present)"
        )

    ws = _wholesaler_for_schema(bind, schema)
    q_orders = f'"{schema}".orders'
    q_payments = f'"{schema}".payments'
    params = {"ws": ws}

    cross = _count(bind, f"""
        SELECT COUNT(*) FROM {q_orders}
        WHERE is_deleted IS FALSE AND wholesaler_id::text <> :ws
    """, params)
    if cross:
        raise PreflightFailure(
            f"{schema}: {cross} order(s) belong to another wholesaler")

    bad_payments = _count(bind, f"""
        SELECT COUNT(*)
        FROM {q_payments} p
        LEFT JOIN {q_orders} o ON o.id = p.order_id
        WHERE p.is_deleted IS FALSE
          AND (
              p.amount IS NULL OR p.amount <= 0
              -- PostgreSQL numerics also admit NaN/Infinity/-Infinity; NaN
              -- and +Infinity are NOT caught by "amount <= 0" (NaN sorts
              -- above every non-NaN value), so they are named explicitly.
              OR p.amount IN ('NaN'::numeric, 'Infinity'::numeric,
                              '-Infinity'::numeric)
              OR p.method IS NULL
              OR p.method NOT IN ('cash', 'transfer', 'credit')
              OR p.status IS NULL
              OR p.status NOT IN ('pending', 'completed')
              OR o.id IS NULL OR o.is_deleted IS TRUE
              OR o.wholesaler_id::text <> :ws
              OR p.retailer_id IS DISTINCT FROM o.retailer_id
          )
    """, params)
    if bad_payments:
        raise PreflightFailure(
            f"{schema}: {bad_payments} invalid effective payment row(s) "
            "(zero/negative/non-finite amounts, unknown methods or statuses, "
            "orphaned, cross-wholesaler or retailer-mismatched history cannot "
            "be explained)")

    duplicate_credit = _count(bind, f"""
        WITH {EFFECTIVE_PER_ORDER.format(payments=q_payments)}
        SELECT COUNT(*) FROM effective_payments WHERE credit_rows > 1
    """)
    if duplicate_credit:
        raise PreflightFailure(
            f"{schema}: {duplicate_credit} order(s) carry duplicate credit "
            "sales")

    # C3 state matrix — every order's history must be explainable.
    matrix_violations = _count(bind, f"""
        WITH {EFFECTIVE_PER_ORDER.format(payments=q_payments)},
        classified AS (
            SELECT o.id, o.status::text AS status, o.total_amount,
                   COALESCE(e.cash_total, 0) AS cash_total,
                   COALESCE(e.credit_total, 0) AS credit_total,
                   COALESCE(e.credit_rows, 0) AS credit_rows
            FROM {q_orders} o
            LEFT JOIN effective_payments e ON e.order_id = o.id
            WHERE o.is_deleted IS FALSE AND o.wholesaler_id::text = :ws
        )
        SELECT COUNT(*) FROM classified
        WHERE (status = ANY(ARRAY['confirmed', 'partially_paid',
                                  'paid', 'fulfilled', 'returned'])
               AND total_amount <= 0)
           OR (status = 'confirmed'
               AND (cash_total <> 0 OR credit_total <> 0))
           OR (status = 'partially_paid'
               AND (credit_total <> 0
                    OR cash_total <= 0 OR cash_total >= total_amount))
           OR (status = ANY(ARRAY['paid', 'fulfilled', 'returned'])
               AND credit_total > 0
               AND (credit_rows <> 1
                    OR credit_total <> total_amount
                    OR cash_total < 0 OR cash_total > credit_total))
           OR (status = ANY(ARRAY['paid', 'fulfilled', 'returned'])
               AND credit_total = 0
               AND cash_total <> total_amount)
           OR (status = ANY(ARRAY['draft', 'cancelled', 'voided'])
               AND (cash_total <> 0 OR credit_total <> 0))
    """, params)
    if matrix_violations:
        raise PreflightFailure(
            f"{schema}: {matrix_violations} order(s) do not fit the C3 "
            "migration state matrix (unexplainable history is rejected, "
            "never repaired)")

    binding_gaps = _count(bind, f"""
        WITH {EFFECTIVE_PER_ORDER.format(payments=q_payments)},
        exposed AS (
            SELECT DISTINCT o.retailer_id::text AS retailer_id
            FROM {q_orders} o
            LEFT JOIN effective_payments e ON e.order_id = o.id
            WHERE o.is_deleted IS FALSE
              AND o.wholesaler_id::text = :ws
              AND (o.status::text = ANY(ARRAY['confirmed', 'partially_paid'])
                   OR COALESCE(e.credit_total, 0) > 0)
        )
        SELECT COUNT(*) FROM exposed r
        WHERE NOT EXISTS (
            SELECT 1 FROM public.wholesaler_retailer_bindings wrb
            WHERE wrb.retailer_id::text = r.retailer_id
              AND wrb.wholesaler_id::text = :ws
              AND wrb.is_deleted IS FALSE
        )
    """, params)
    if binding_gaps:
        raise PreflightFailure(
            f"{schema}: {binding_gaps} retailer(s) with hold-bearing or "
            "credit-exposed orders lack a live binding")

    # P14: the pre-existing cache must equal the 038 exposure-only formula
    # EXACTLY. Drift is unexplainable data and fails closed; this migration
    # never "repairs" the old cache silently.
    cache_diffs = _count(bind, f"""
        WITH {EFFECTIVE_PER_ORDER.format(payments=q_payments)},
        exposure AS (
            SELECT o.retailer_id::text AS retailer_id,
                   SUM(e.credit_total - e.cash_total) AS exposure_total
            FROM {q_orders} o
            JOIN effective_payments e ON e.order_id = o.id
            WHERE o.is_deleted IS FALSE
              AND o.wholesaler_id::text = :ws
              AND e.credit_total > 0
            GROUP BY o.retailer_id
        )
        SELECT COUNT(*)
        FROM public.wholesaler_retailer_bindings wrb
        LEFT JOIN exposure x ON x.retailer_id = wrb.retailer_id::text
        WHERE wrb.is_deleted IS FALSE
          AND wrb.wholesaler_id::text = :ws
          AND wrb.outstanding_balance
              <> COALESCE(x.exposure_total, 0)::numeric(12, 2)
    """, params)
    if cache_diffs:
        samples = bind.execute(sa.text(f"""
            WITH {EFFECTIVE_PER_ORDER.format(payments=q_payments)},
            exposure AS (
                SELECT o.retailer_id::text AS retailer_id,
                       SUM(e.credit_total - e.cash_total) AS exposure_total
                FROM {q_orders} o
                JOIN effective_payments e ON e.order_id = o.id
                WHERE o.is_deleted IS FALSE
                  AND o.wholesaler_id::text = :ws
                  AND e.credit_total > 0
                GROUP BY o.retailer_id
            )
            SELECT wrb.retailer_id::text, wrb.outstanding_balance::text,
                   COALESCE(x.exposure_total, 0)::text
            FROM public.wholesaler_retailer_bindings wrb
            LEFT JOIN exposure x ON x.retailer_id = wrb.retailer_id::text
            WHERE wrb.is_deleted IS FALSE
              AND wrb.wholesaler_id::text = :ws
              AND wrb.outstanding_balance
                  <> COALESCE(x.exposure_total, 0)::numeric(12, 2)
            LIMIT 5
        """), params).fetchall()
        sample_text = "; ".join(
            f"retailer={s[0]} cache={s[1]} expected_038={s[2]}" for s in samples)
        raise PreflightFailure(
            f"{schema}: P14 cache proof failed for {cache_diffs} binding(s) "
            f"(cache must equal the 038 exposure-only formula exactly); "
            f"samples: {sample_text}")


